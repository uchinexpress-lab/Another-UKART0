// HTML-escape customer-supplied text before interpolating it into email HTML.
// Prevents HTML/JS injection from user-controlled fields (names, addresses, etc.).
export function escapeHtml(value: unknown): string {
  if (value === null || value === undefined) return "";
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}